#!/usr/bin/env node
/* ==========================================================================
   bundle.mjs — one self-contained page, one CSS file. Zero dependencies.

     node design/tools/bundle.mjs

   Writes to design/dist/ (generated; don't edit):

     flashcards.css     tokens + base + components + wire, imports inlined and
                        wrapped in their layers. What an app links. Fonts stay
                        as files: ../fonts/archivo-latin-var.woff2.
     style-sheet.html   index.html with every stylesheet and the font inlined.
                        One file you can email, drop in a chat, or open offline.

   Nothing here is needed to USE the sheet. index.html opens straight from disk.
   ========================================================================== */

import { readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");
const read = (p) => readFileSync(p, "utf8");

/* Inline every @import, wrapping it in its layer if it names one. */
function inlineImports(file) {
  return read(file).replace(
    /@import\s+url\(\s*["']?([^"')]+)["']?\s*\)\s*(?:layer\(\s*([^)]+?)\s*\))?\s*;/g,
    (_, url, layer) => {
      const body = inlineImports(resolve(dirname(file), url)).trim();
      return layer ? `@layer ${layer} {\n${body}\n}` : body;
    },
  );
}

/* Replace url(../fonts/x.woff2) with a data URI. Paths are relative to css/. */
function inlineFonts(css, cssDir) {
  return css.replace(/url\(\s*["']?(\.\.\/fonts\/[^"')]+\.woff2)["']?\s*\)/g, (_, url) => {
    const b64 = readFileSync(resolve(cssDir, url)).toString("base64");
    return `url("data:font/woff2;base64,${b64}")`;
  });
}

const banner = (what) => `/* ${what}. Generated by tools/bundle.mjs, do not edit. */\n`;

mkdirSync(DIST, { recursive: true });

/* 1. the app-facing stylesheet */
const cssEntry = join(ROOT, "css", "flashcards.css");
const bundle = inlineImports(cssEntry);
writeFileSync(join(DIST, "flashcards.css"), banner("flashcards.css") + bundle);

/* 2. the single-file page */
let html = read(join(ROOT, "index.html"));
html = html.replace(/<link rel="stylesheet" href="([^"]+)"\s*\/?>/g, (_, href) => {
  const file = resolve(ROOT, href);
  const css = /flashcards\.css$/.test(href) ? bundle : read(file);
  return `<style>\n${inlineFonts(css, join(ROOT, "css"))}\n</style>`;
});
if (/<link rel="stylesheet"/.test(html)) throw new Error("a stylesheet link was left un-inlined");
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by tools/bundle.mjs from index.html. Do not edit. -->");
writeFileSync(join(DIST, "style-sheet.html"), html);

const kb = (p) => `${(statSync(p).size / 1024).toFixed(0)} KB`;
console.log(`dist/flashcards.css     ${kb(join(DIST, "flashcards.css"))}`);
console.log(`dist/style-sheet.html   ${kb(join(DIST, "style-sheet.html"))}`);
